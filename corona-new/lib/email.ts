import { Resend } from 'resend';

const resend = process.env.RESEND_API_KEY ? new Resend(process.env.RESEND_API_KEY) : null;

interface InquiryEmailData {
  customerName: string;
  customerPhone: string;
  customerEmail: string;
  productTitle: string;
  quantity: number;
  notes?: string;
}

export async function sendInquiryEmail(data: InquiryEmailData) {
  const { customerName, customerPhone, customerEmail, productTitle, quantity, notes } = data;

  try {
    if (!resend) {
      console.warn('Resend API key is missing. Email not sent.');
      return { success: false, error: 'API key missing' };
    }
    const { data: resendData, error } = await resend.emails.send({
      from: 'Tawwakal Automation <onboarding@resend.dev>',
      to: process.env.EMAIL_TO || 'info@tawwakalautomation.com',
      subject: `New Equipment Quotation Request: ${productTitle}`,
      html: `
        <div style="font-family: Arial, sans-serif; padding: 20px; color: #202A3A; text-align: left;">
          <h2 style="color: #0B153B;">Tawwakal Automation — New Equipment Quotation Request</h2>
          <p>A new quotation request has been received for <strong>${productTitle}</strong>.</p>
          
          <div style="background: #F4F7FA; padding: 15px; border-radius: 6px; margin: 20px 0; border: 1px solid #DDE4EC;">
            <h3 style="margin-top: 0; color: #0B153B;">Customer Details</h3>
            <p><strong>Name / Company:</strong> ${customerName}</p>
            <p><strong>Phone:</strong> ${customerPhone}</p>
            <p><strong>Email:</strong> ${customerEmail || 'Not provided'}</p>
            <hr style="border: 0; border-top: 1px solid #DDE4EC;" />
            <h3 style="margin-top: 15px; color: #0B153B;">Requirement Details</h3>
            <p><strong>Product:</strong> ${productTitle}</p>
            <p><strong>Quantity:</strong> ${quantity}</p>
            <p><strong>Notes / Specifications:</strong> ${notes || 'No extra notes provided.'}</p>
          </div>
          
          <p style="font-size: 12px; color: #8A98A8;">This email was automatically generated by the Tawwakal Automation website.</p>
        </div>
      `,
    });

    if (error) {
      console.error('Resend inquiry email error:', error);
      return { success: false, error };
    }

    console.log('Inquiry email sent via Resend:', resendData?.id);
    return { success: true, messageId: resendData?.id };
  } catch (error) {
    console.error('Error sending inquiry email via Resend:', error);
    return { success: false, error };
  }
}

